class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *a, **kw):
        super().__init__(*a, directory=str(SITE), **kw)

    def log_message(self, fmt, *args):
        pass  # quiet

    def send_response(self, code, message=None):
        super().send_response(code, message)
        self.send_header("Cache-Control", "no-store")  # page must never go stale

    def do_GET(self):
        # Identity endpoint so launcher/serve.sh can tell "ours already
        # running" apart from a foreign process holding the port.
        if self.path == "/api/health":
            return self._json(200, {"app": "wednesday-dashboard", "ok": True})
        if self.path == "/api/chatlog":
            # Live-poll endpoint for the chat-with-Wed view (no regeneration).
            # Each message is joined with its ack state (key = message ts) so
            # the sidebar renders seen/actioning/done/action_requested live.
            cpath = ROOT / "0_Brain" / "dashboard" / "data" / "chat_log.json"
            log = json.loads(cpath.read_text()) if cpath.exists() else []
            if not isinstance(log, list):
                log = []
            apath = ROOT / "0_Brain" / "dashboard" / "data" / "ack_state.json"
            ack = json.loads(apath.read_text()) if apath.exists() else {}
            if not isinstance(ack, dict):
                ack = {}
            out = []
            for m in log:
                m = dict(m)
                a = ack.get(m.get("ts", ""))
                if isinstance(a, dict) and a.get("state"):
                    m["ack"] = a
                out.append(m)
            return self._json(200, {"messages": out})
        return super().do_GET()

    def _json(self, code, payload):
        body = json.dumps(payload).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

