def gql(query, variables=None):
    req = urllib.request.Request("https://api.linear.app/graphql",
        data=json.dumps({"query": query, "variables": variables or {}}).encode(),
        headers={"Authorization": ENV["LINEAR_API_KEY"], "Content-Type": "application/json"})
    r = json.load(urllib.request.urlopen(req, timeout=20))
    if "errors" in r:
        raise RuntimeError(r["errors"])
    return r

def issue_id(identifier):
    num = int(identifier.split("-")[1])
    r = gql('query($n:Float!){ issues(filter:{team:{key:{eq:"WED"}}, number:{eq:$n}}){ nodes{ id } } }',
            {"n": num})
    return r["data"]["issues"]["nodes"][0]["id"]

def state_id(name):
    r = gql('query($id:String!){ team(id:$id){ states{ nodes{ id name } } } }',
            {"id": ENV["LINEAR_TEAM_ID"]})
    return {s["name"]: s["id"] for s in r["data"]["team"]["states"]["nodes"]}[name]

