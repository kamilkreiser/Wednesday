//! QA-SCANNER-CORE item 8: docs/SCANNER.md sentences tested once each, the builder's over-flag table
//! re-run, and an everyday corpus written by QA (NOT real traffic) to estimate how often an ordinary
//! agent-to-agent message flags.
use coagent_scanner::{scan, Kind, Verdict};

fn kinds(v: &Verdict) -> String {
    match v {
        Verdict::Clean => "CLEAN".into(),
        Verdict::Flagged(f) => f.iter().map(|x| format!("{:?}", x.kind())).collect::<Vec<_>>().join("+"),
    }
}

