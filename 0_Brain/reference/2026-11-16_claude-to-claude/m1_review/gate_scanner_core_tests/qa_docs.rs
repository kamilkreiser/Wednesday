#[test]
fn qa_everyday_corpus() {
    let mut flagged = 0;
    let mut by_kind = std::collections::BTreeMap::new();
    for s in EVERYDAY {
        let v = scan(s);
        if v.share_flagged() {
            flagged += 1;
            for f in v.findings() {
                *by_kind.entry(format!("{:?}", f.kind())).or_insert(0) += 1;
            }
            println!("EVERYDAY FLAG | {:<40} | {s:?}", kinds(&v));
        }
    }
    let n = EVERYDAY.len();
    println!("EVERYDAY: {n} sentences, {flagged} flagged ({:.1}%), by kind {by_kind:?}", 100.0 * flagged as f64 / n as f64);
    assert!(n >= 200, "control: at least 200 sentences");
}

